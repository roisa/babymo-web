/**
 * Builds the clip list for the story recorder (babymo-app www/tools/rekam-cerita.html):
 * every page of every kids' story, in Indonesian and English — the title, each page,
 * and each quote — grouped by series. Re-run after adding or editing stories:
 *
 *   npx tsx scripts/build-rekam-cerita.ts ../babymo-app/www/tools/rekam-cerita-data.js
 *
 * Clip ids are stable (<slug>.<lang>.<nn>, nn = 00 title, 01… pages, 05q quote on page 5),
 * and `f` is where the finished narration will live: story-voice/<lang>/<slug>/<nn>.mp3.
 * A take already recorded keeps its id as long as the page number stays the same.
 */
import fs from "node:fs";
import { getAllCatatan } from "../lib/content/catatan";
import { getBookPages } from "../lib/cerita/picture-books";
import { SERIES } from "../lib/cerita/series";

type Clip = { id: string; s: string; g: string; t: string; h: string; l: "id" | "en"; k: string; f: string; key: string };
const LANGS = ["id", "en"] as const;
const out = process.argv[2] ?? "../babymo-app/www/tools/rekam-cerita-data.js";

const clean = (s: string) =>
  s.replace(/\*\*([^*]+)\*\*/g, "$1").replace(/\*([^*]+)\*/g, "$1").replace(/^>\s?/gm, "").replace(/\s+/g, " ").trim();

const stories = getAllCatatan().filter((c) => c.kind === "story");
const bySlug = new Map(stories.map((s) => [s.slug, s]));
const inSeries = new Set(SERIES.flatMap((x) => x.books));

const sections: { s: string; id: string; en: string; ic: string }[] = [];
const order: { s: string; slug: string }[] = [];
for (const x of SERIES) {
  const books = x.books.filter((b) => bySlug.has(b));
  if (!books.length) continue;
  sections.push({ s: x.key, id: x.title.id, en: x.title.en, ic: x.emoji });
  books.forEach((slug) => order.push({ s: x.key, slug }));
}
const loose = stories.filter((s) => !inSeries.has(s.slug));
const loosePB = loose.filter((s) => getBookPages(s.slug));
const short = loose.filter((s) => !getBookPages(s.slug));
if (loosePB.length) {
  sections.push({ s: "buku-lain", id: "Buku lainnya", en: "Other books", ic: "📗" });
  loosePB.forEach((s) => order.push({ s: "buku-lain", slug: s.slug }));
}
if (short.length) {
  sections.push({ s: "cerita-pendek", id: "Cerita pendek", en: "Short stories", ic: "📝" });
  short.forEach((s) => order.push({ s: "cerita-pendek", slug: s.slug }));
}

const clips: Clip[] = [];
const pad = (n: number) => String(n).padStart(2, "0");
for (const { s, slug } of order) {
  const st = bySlug.get(slug)!;
  const book = getBookPages(slug);
  for (const l of LANGS) {
    // pages: picture books use their pages; other stories use their paragraphs (as Book Mode does)
    const pages: { text: string; quote?: string }[] = book
      ? book.pages.map((p) => ({ text: clean(p.text[l]), quote: p.quote ? clean(p.quote[l]) : undefined }))
      : st.body[l].trim().split(/\n\s*\n/).map((raw) => ({ text: clean(raw) })).filter((p) => p.text);
    const n = pages.length;
    const add = (nn: string, t: string, h: string, k: string) =>
      clips.push({ id: `${slug}.${l}.${nn}`, s, g: st.title.id, t, h, l, k, f: `story-voice/${l}/${slug}/${nn}.mp3`, key: `${slug}.${l}.${nn}` });
    add("00", st.title[l], "🏷️ Judul / Title" + (l === "en" ? " · " + st.title.en : ""), "title");
    pages.forEach((p, i) => {
      add(pad(i + 1), p.text, `📖 ${i + 1}/${n}`, "page");
      if (p.quote) add(pad(i + 1) + "q", p.quote, `📜 Kutipan / Quote · ${i + 1}/${n} — pelan & khidmat / slow & calm`, "quote");
    });
  }
}

const count = sections.map((x) => `${x.s} ${clips.filter((c) => c.s === x.s).length}`).join(", ");
const js =
  `/* Clip list for rekam-cerita.html — generated by babymo-web scripts/build-rekam-cerita.ts; do not edit.\n` +
  `   ${stories.length} stories, ${clips.length} clips (ID + EN): ${count} */\n` +
  `window.REKAM_SECTIONS=${JSON.stringify(sections)};\n` +
  `window.REKAM=[\n${clips.map((c) => JSON.stringify(c)).join(",\n")}\n];\n`;
fs.writeFileSync(out, js);
console.log(`wrote ${out}: ${clips.length} clips in ${sections.length} sections (${(js.length / 1024) | 0} KB)`);
